// Quick smoke + screenshot driver (dev aid). Run under xvfb-run.
const { _electron: electron, chromium } = require('playwright');
const path = require('path'); const fs = require('fs');
const OUT = process.env.SHOTS || path.join(__dirname, '..', '..', 'test-output', 'shots');
const SAMPLES = process.env.SAMPLES;
const DATA = process.env.DATA || fs.mkdtempSync('/tmp/cmbdata-');
fs.mkdirSync(OUT, { recursive: true });
const sleep = ms => new Promise(r => setTimeout(r, ms));
let stepN = 0; const step = (ms) => { console.log('step', ++stepN, new Date().toISOString().slice(11,19)); return sleep(ms); };
(async () => {
  const app = await electron.launch({ executablePath: require('electron'), args: [path.join(__dirname, '..', '..'), '--no-sandbox'], env: Object.assign({}, process.env, { CMB_TEST: '1', CMB_SHOW: '1', CMB_DATA_DIR: DATA, CMB_NO_SANDBOX: '1' }) });
  app.on('console', m => { if (m.type() === 'error') console.log('[console]', m.text()); });
  const host = await app.firstWindow();
  host.on('pageerror', e => console.log('[host pageerror]', e.message));
  await app.evaluate(({ BrowserWindow }) => { const w = BrowserWindow.getAllWindows()[0]; w.setSize(1600, 1000); });
  await step(1500);
  const inv = (ch, p) => { if (ch !== 'library:list') console.log('inv', ch); return host.evaluate(([c, x]) => window.cmb.invoke(c, x), [ch, p]); };
  await inv('library:importPaths', [SAMPLES]);
  for (let i = 0; i < 120; i++) { const l = await inv('library:list'); if (!l.songs.some(s => s.status === 'unchecked')) break; await step(500); }
  const lib = await inv('library:list');
  console.log('songs', lib.songs.length, 'ok', lib.songs.filter(s => s.status === 'ok').length);
  await host.evaluate(() => App.show('library')); await step(800);
  await host.screenshot({ path: path.join(OUT, '01-library.png') });
  const pl = await inv('playlists:create', { name: 'Pub Classics' });
  await inv('playlists:add', { id: pl.id, songIds: lib.songs.map(s => s.id) });
  await host.evaluate(() => App.show('playlists')); await step(800);
  await host.screenshot({ path: path.join(OUT, '02-playlists.png') });
  const g = await inv('games:create', { name: 'Thursday Night Music Bingo', venue: 'The Red Lion', playlistId: pl.id, cards: 100, settings: { clipMode: 'full', autoAdvanceGap: 1 } });
  console.log('game', g.id, g.cards);
  const pdf = path.join(OUT, 'cards.pdf');
  const r = await inv('cards:exportPdf', { id: g.id, file: pdf, confirmLock: true });
  console.log('pdf', JSON.stringify(r));
  await host.evaluate(() => App.show('cards')); await step(1200);
  await host.screenshot({ path: path.join(OUT, '03-cards.png') });
  await host.evaluate(() => App.show('create')); await step(800);
  await host.screenshot({ path: path.join(OUT, '04-create-wizard.png') });
  await inv('audience:open');
  await step(2500);
  await host.evaluate(() => App.cmd('startRound', { round: 1 }));
  await step(21000);
  const wins = app.windows();
  const aud = wins.find(w => w.url().includes('audience'));
  await app.evaluate(({ BrowserWindow }) => { BrowserWindow.getAllWindows().forEach(w => { if (w.getTitle().includes('Audience')) w.setContentSize(1600, 900); }); });
  await step(1500);
  await aud.screenshot({ path: path.join(OUT, '05-audience-tv.png') });
  await host.evaluate(() => App.show('host')); await step(800);
  await host.screenshot({ path: path.join(OUT, '06-host-game.png') });
  // checker
  // Claim Freeze with two cards — one valid (we force its row to count via technical credit+mark), one invalid
  const gs = (await inv('game:state')).game;
  await host.evaluate(() => { App.openChecker(); }); await step(1200);
  await host.fill('#ckNo', '2'); await host.press('#ckNo', 'Enter'); await step(700);
  await host.fill('#ckNo', '1'); await host.press('#ckNo', 'Enter'); await step(900);
  await host.screenshot({ path: path.join(OUT, '07-bingo-check.png') });
  await host.keyboard.press('Escape'); await step(500);
  await host.screenshot({ path: path.join(OUT, '07b-host-frozen.png') });
  await host.evaluate(() => { App.creditDialog(); }); await step(700);
  await host.screenshot({ path: path.join(OUT, '07c-credit-dialog.png') });
  await host.keyboard.press('Escape'); await step(300);
  await host.evaluate(() => App.show('backup')); await step(1200);
  await host.screenshot({ path: path.join(OUT, '07d-backup.png') });
  await host.evaluate(() => App.show('settings')); await step(1000);
  await host.screenshot({ path: path.join(OUT, '07e-settings.png'), fullPage: true });
  // celebrate on TV
  // remote
  const info = await inv('remote:info');
  await host.evaluate(() => App.show('mobile')); await step(800);
  await host.screenshot({ path: path.join(OUT, '08-mobile-connection.png') });
  const br = await chromium.launch();
  const ctx = await br.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true, userAgent: 'Mozilla/5.0 (iPhone; CPU iPhone OS 17_0 like Mac OS X) AppleWebKit/605.1.15 Mobile/15E148' });
  const ph = await ctx.newPage();
  ph.on('pageerror', e => console.log('[phone pageerror]', e.message));
  await ph.goto(`http://127.0.0.1:${info.port}/`); await step(800);
  await ph.screenshot({ path: path.join(OUT, '09-phone-pair.png') });
  await ph.goto(`http://127.0.0.1:${info.port}/#pin=${info.pin}`); await ph.reload(); await step(2000);
  await ph.screenshot({ path: path.join(OUT, '10-phone-play.png') });
  await ph.click('#tabs button[data-tab=rounds]'); await step(500);
  await ph.screenshot({ path: path.join(OUT, '11-phone-rounds.png') });
  await ph.click('#tabs button[data-tab=play]'); await step(300);
  await ph.screenshot({ path: path.join(OUT, '10b-phone-play-frozen.png') });
  await ph.click('#bingoFab'); await step(800);
  for (const k of ['4', '2']) await ph.click(`#keypad button:text-is("${k}")`);
  await ph.screenshot({ path: path.join(OUT, '12-phone-keypad.png') });
  await ph.click('#ckGo'); await step(1200);
  await ph.screenshot({ path: path.join(OUT, '13-phone-result.png'), fullPage: true });
  await br.close();
  console.log('state', JSON.stringify((await inv('game:state')).game.totals));
  await app.close();
  console.log('DATA', DATA);
})().catch(e => { console.error('FAILED', e); process.exit(1); });
